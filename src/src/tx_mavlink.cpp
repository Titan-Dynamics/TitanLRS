    case RATE_LORA_900_150HZ: case RATE_LORA_2G4_150HZ: case RATE_LORA_DUAL_150HZ: return "150Hz";
    case RATE_LORA_900_200HZ: case RATE_LORA_2G4_200HZ: return "200Hz";
