static void writeToGcs(const uint8_t *data, uint16_t size)
{
    TxUSB->write(data, size);
#if defined(PLATFORM_STM32)
    MavlinkUdp_Send(data, size);
#endif
#if defined(PLATFORM_ESP32)
    if (backpackGetsMavlink())
    {
        BackpackOrLogStrm->write(data, size);
    }
#endif
}

static bool queueFrame(const uint8_t *frame, uint16_t len)
{
    if (queuedLen + len > sizeof(queuedFrames))
        return false;
    memcpy(queuedFrames + queuedLen, frame, len);
    queuedLen += len;
    return true;
}

static void flushQueuedFrames()
{
    // Only between frames from the vehicle, so the TX's frames are not spliced into the middle of one
    if (queuedLen != 0 && vehicleRxStatus.parse_state <= MAVLINK_PARSE_STATE_IDLE)
    {
        writeToGcs(queuedFrames, queuedLen);
        queuedLen = 0;
    }
}

static uint8_t fallbackSysid() { return 1; }

static void start(uint32_t now)
{
    if (started)
        return;
    started = true;
    MavParamServer::Config cfg = {};
    cfg.compid = TLRS_MAV_TX_COMPID;
    cfg.fallbackSysid = fallbackSysid;
    cfg.heartbeatWaitMs = HEARTBEAT_WAIT;
    cfg.replyDelayMs = PARAM_REPLY_DELAY;
    cfg.maxFramesPerTick = 4;
    cfg.swVersion = MavParamServer::versionFromString(version);
    server.begin(params, sizeof(params) / sizeof(params[0]), cfg, queueFrame, now);
}

void TxMavlink_ProcessFromGcs(txMavlinkGcsLink_e link, const uint8_t *data, uint16_t size)
{
    const uint32_t now = millis();
    start(now);
    for (uint16_t i = 0; i < size; i++)
    {
        mavlink_message_t msg;
        mavlink_status_t status;
        if (mavlink_frame_char_buffer(&gcsRxMsg[link], &gcsRxStatus[link], data[i], &msg, &status) == MAVLINK_FRAMING_OK)
        {
            server.handleGcsMessage(&msg, now);
        }
    }
}

void TxMavlink_ForwardToGcs(const uint8_t *data, uint16_t size)
{
    // Frames arrive over the air in chunks that are not aligned to frame boundaries,
    // so write out whole runs of bytes and slot the TX's frames in where a frame ends
    uint16_t begin = 0;
    for (uint16_t i = 0; i < size; i++)
    {
        mavlink_message_t msg;
        mavlink_status_t status;
        if (mavlink_frame_char_buffer(&vehicleRxMsg, &vehicleRxStatus, data[i], &msg, &status) == MAVLINK_FRAMING_OK)
        {
            server.handleVehicleMessage(&msg);
        }
        if (queuedLen != 0 && vehicleRxStatus.parse_state <= MAVLINK_PARSE_STATE_IDLE)
        {
            writeToGcs(data + begin, i + 1 - begin);
            begin = i + 1;
            flushQueuedFrames();
        }
    }
    if (begin < size)
    {
        writeToGcs(data + begin, size - begin);
    }
    lastVehicleByte = millis();
}

void TxMavlink_Update(uint32_t now)
{
    start(now);

    if (vehicleRxStatus.parse_state > MAVLINK_PARSE_STATE_IDLE && now - lastVehicleByte > DOWNLINK_FRAME_TIMEOUT)
    {
        // The rest of the frame is never coming, the GCS will discard what it has as a bad frame
        vehicleRxStatus.parse_state = MAVLINK_PARSE_STATE_IDLE;
    }

    server.tick(now);
    updateLinkReports(now);
    flushQueuedFrames();
}
