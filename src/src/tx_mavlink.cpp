static bool isWhole(float value, float max)
{
    return value >= 0 && value <= max && value == (float)(uint16_t)value;
}

// The doc comments on each entry are read by python/gen_param_metadata.py

static float getPacketRate() { return get_elrs_airRateConfig(config.GetRate())->enum_rate; }
static const char *setPacketRate(float value)
{
    if (!isWhole(value, 255))
        return "not a packet rate";
    for (uint8_t index = 0; index < RATE_MAX; index++)
    {
        const expresslrs_mod_settings_s *modParams = get_elrs_airRateConfig(index);
        if (modParams->enum_rate != (uint8_t)value)
            continue;
        if (!isSupportedRFRate(index))
            break;
        // The same rates the Lua offers
        if (modParams->interval * modParams->numOfSends < handset->getMinPacketInterval())
            return "too fast for the handset link";
        crsfTransmitter.SetPacketRateIdx(index, true);
        return nullptr;
    }
    return "not supported on this hardware";
}

// From the configured rate, which the radio switches to once the sync packets announcing it are out
static float getPacketHz()
{
    const int32_t interval = get_elrs_airRateConfig(config.GetRate())->interval;
    return (1000000 + interval / 2) / interval;
}

static float getTlmRatio() { return config.GetTlm(); }
static const char *lockTlmRatio() { return crsfTransmitter.TlmRatioLockReason(); }
static const char *setTlmRatio(float value)
{
    if (!isWhole(value, TLM_RATIO_DISARMED))
        return "not a ratio";
    crsfTransmitter.SetTlmRatio((uint8_t)value);
    return nullptr;
}

static bool hasSwitchMode() { return !firmwareOptions.is_airport; }
static float getSwitchMode() { return config.GetSwitchMode(); }
static const char *lockSwitchMode() { return crsfTransmitter.SwitchModeLockReason(); }
static const char *setSwitchMode(float value)
{
    if (!isWhole(value, OtaIsFullRes ? 2 : 1))
        return "not a mode at this rate";
    crsfTransmitter.SetSwitchMode((uint8_t)value);
    return nullptr;
}

static bool hasAntennaMode() { return isDualRadio(); }
static float getAntennaMode() { return config.GetAntennaMode(); }
static const char *setAntennaMode(float value)
{
    if (!isWhole(value, TX_RADIO_MODE_SWITCH))
        return "not an antenna mode";
    if (get_elrs_airRateConfig(config.GetRate())->radio_type == RADIO_TYPE_LR1121_LORA_DUAL && value != TX_RADIO_MODE_GEMINI)
        return "dual band rates use Gemini";
    crsfTransmitter.SetAntennaMode((uint8_t)value);
    return nullptr;
}

static float getLinkMode() { return pendingLinkMode >= 0 ? pendingLinkMode : config.GetLinkMode(); }
static const char *setLinkMode(float value)
{
    if (!isWhole(value, TX_MAVLINK_MODE))
        return "not a link mode";
    if (value == getLinkMode())
        return nullptr;
    // Leaving MAVLink keeps the switch mode, so the RX can follow from the sync packet while linked
    pendingLinkMode = (int8_t)value;
    deferExecutionMillis(LINK_MODE_APPLY_DELAY, []() {
        config.SetLinkMode(pendingLinkMode);
        pendingLinkMode = -1;
    });
    return nullptr;
}

static bool hasRadio() { return HAS_RADIO; }
static float getPower() { return powerLevelsMw[config.GetPower()]; }
static const char *setPower(float value)
{
    for (uint8_t power = POWERMGNT::getMinPower(); power <= POWERMGNT::getMaxPower(); power++)
    {
        if (value == powerLevelsMw[power])
        {
            crsfTransmitter.SetPowerMax(power);
            return nullptr;
        }
    }
    return "not a power level of this TX";
}

static float getDynamicPower() { return config.GetDynamicPower() ? config.GetBoostChannel() + 1 : 0; }
static const char *setDynamicPower(float value)
{
    if (!isWhole(value, 5))
        return "not a dynamic power mode";
    crsfTransmitter.SetDynamicPower((uint8_t)value);
    return nullptr;
}

static bool hasFan() { return GPIO_PIN_FAN_EN != UNDEF_PIN || GPIO_PIN_FAN_PWM != UNDEF_PIN; }
static float getFanThreshold() { return config.GetPowerFanThreshold(); }
static const char *setFanThreshold(float value)
{
    if (!isWhole(value, PWR_COUNT))
        return "not a threshold";
    config.SetPowerFanThreshold((uint8_t)value);
    return nullptr;
}

