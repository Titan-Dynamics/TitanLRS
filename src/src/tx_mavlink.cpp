// RSSI as MLRS wants it with MLRS_FLAG_RSSI_DBM: 1..254 for -1..-254 dBm, 0 for no reception
static uint8_t rssiMagnitude(int8_t dbm)
{
    return dbm < 0 ? (uint8_t)(-dbm) : 0;
}

static void sendLinkStats()
{
    const bool linked = connectionState == connected;
    mavlink_mlrs_radio_link_stats_t stats = {};
    stats.flags = MLRS_FLAG_RSSI_DBM;
    if (linkStats.active_antenna)
        stats.flags |= MLRS_FLAG_RX_RECEIVE_ANTENNA2;
    if (!isDualRadio() || config.GetAntennaMode() != TX_RADIO_MODE_ANT_2)
        stats.flags |= MLRS_FLAG_TX_TRANSMIT_ANTENNA1;
    if (isDualRadio() && config.GetAntennaMode() != TX_RADIO_MODE_ANT_1)
        stats.flags |= MLRS_FLAG_TX_TRANSMIT_ANTENNA2;
    // There is one LQ for the uplink; the MAVLink stream's own LQ is not measured
    stats.rx_LQ_rc = linked ? linkStats.uplink_Link_quality : 0;
    stats.rx_LQ_ser = UINT8_MAX;
    stats.rx_rssi1 = linked ? rssiMagnitude((int8_t)linkStats.uplink_RSSI_1) : 0;
    // A receiver with one antenna never reports the second
    stats.rx_rssi2 = !linked ? 0 : (linkStats.uplink_RSSI_2 == 0 ? UINT8_MAX : rssiMagnitude((int8_t)linkStats.uplink_RSSI_2));
    stats.rx_snr1 = linked ? linkStats.uplink_SNR : INT8_MAX;
    stats.rx_snr2 = INT8_MAX;
    // The receiver's telemetry packets carry the MAVLink downlink
    stats.tx_LQ_ser = linked ? linkStats.downlink_Link_quality : 0;
    stats.tx_rssi1 = linked ? rssiMagnitude((int8_t)linkStats.downlink_RSSI_1) : 0;
    stats.tx_rssi2 = !linked ? 0 : (isDualRadio() ? rssiMagnitude((int8_t)linkStats.downlink_RSSI_2) : UINT8_MAX);
    stats.tx_snr1 = linked ? linkStats.downlink_SNR : INT8_MAX;
    stats.tx_snr2 = INT8_MAX;
    mavlink_message_t msg;
    mavlink_msg_mlrs_radio_link_stats_encode(0, 0, &msg, &stats);
    server.sendAsComponent(&msg, MAVLINK_MSG_ID_MLRS_RADIO_LINK_STATS_MIN_LEN, MAVLINK_MSG_ID_MLRS_RADIO_LINK_STATS_CRC);
}

static void buildLinkInformation(mavlink_mlrs_radio_link_information_t *info)
{
    const expresslrs_mod_settings_s *modParams = ExpressLRS_currAirRate_Modparams;
    const uint16_t frameRate = (1000000 + modParams->interval / 2) / modParams->interval;
    memset(info, 0, sizeof(*info));
    info->type = MLRS_LINK_TYPE_EXPRESSLRS;
    info->mode = modParams->enum_rate;
    info->tx_power = powerLevelsDbm[POWERMGNT::currPower()];
    // The receiver's telemetry power is not part of its link statistics
    info->rx_power = INT8_MAX;
    info->tx_frame_rate = frameRate;
    info->rx_frame_rate = ExpressLRS_currTlmDenom > 1 ? frameRate / ExpressLRS_currTlmDenom : 0;
    strncpy(info->mode_str, rateName(modParams->enum_rate), sizeof(info->mode_str));
    strncpy(info->band_str, modParams->radio_type == RADIO_TYPE_LR1121_LORA_DUAL ? "X-Band" : FHSSgetRegulatoryDomain(), sizeof(info->band_str));
    // Both ends run the same rate, so the rate table's sensitivity applies to both
    const int16_t sensitivity = get_elrs_RFperfParams(modParams->index)->RXsensitivity;
    info->tx_receive_sensitivity = info->rx_receive_sensitivity = sensitivity < 0 && sensitivity > -256 ? -sensitivity : 0;
}

static void sendLinkInformation(const mavlink_mlrs_radio_link_information_t *info)
{
    mavlink_message_t msg;
    mavlink_msg_mlrs_radio_link_information_encode(0, 0, &msg, info);
    if (server.sendAsComponent(&msg, MAVLINK_MSG_ID_MLRS_RADIO_LINK_INFORMATION_MIN_LEN, MAVLINK_MSG_ID_MLRS_RADIO_LINK_INFORMATION_CRC))
    {
        sentInformation = *info;
    }
}

static void updateLinkReports(uint32_t now)
{
    // Only once the TX knows the vehicle's system ID, so the GCS files them under the vehicle
    if (!server.ready() || now - lastLinkStats < firmwareOptions.tlm_report_interval)
        return;
    lastLinkStats = now;
    sendLinkStats();

    mavlink_mlrs_radio_link_information_t info;
    buildLinkInformation(&info);
    if (now - lastLinkInformation >= LINK_INFORMATION_INTERVAL || memcmp(&info, &sentInformation, sizeof(info)) != 0)
    {
        lastLinkInformation = now;
        sendLinkInformation(&info);
    }
}

